#pragma once

#ifndef CV_DYNAMIC_DIPLO_MANAGER_H
#define CV_DYNAMIC_DIPLO_MANAGER_H

// XANA: 10-27-2026 LLM Text Diplomacy Generation - bounded worker mailbox

#include <vector>
#include "CvCriticalSectionMutex.h"
#include "CvEnums.h"
#include "CvStructs.h"

class CvDynamicDiploManager
{
	friend class CvGame; // XANA (note): Only the CvGame class needs to initialize or reset this dynamic response manager to default values. No need for other classes to have the same level of access!
public:
	static CvDynamicDiploManager& getInstance(); // Construct on the main thread before launching a worker.
	static CvDynamicDiploManager const& getConstInstance() { return getInstance(); } // XANA (note): main game thread - acccess for reading permissions ONLY!

	// The only worker entry point. Copy raw response bytes from WinINet into a
	// bounded mailbox. This path performs no STL allocation or game API calls.
	bool submitResponse(unsigned long ulSession, PlayerTypes eAIPlayer,
		DiploCommentTypes eComment, int iGroupIndex, const char* pszText, int iLength);

	// Main-thread request setup and mailbox import. Do not construct, destroy or
	// pass STL-backed prompt/result objects on the worker: debug DLL allocation
	// operators can call the game executable's memory manager.
	unsigned long getSessionID() const;
	bool registerPrompt(LLMPromptData const& kPrompt);
	void cancelPrompt(unsigned long ulSession, PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex);
	void processPendingResponses();

	// Called by main game thread to assign response objects to LLM prompt structures
	int getAvailableResponseGroupID(PlayerTypes eAIPlayer, DiploCommentTypes eComment) const;

	// Main-thread display selection: filters atomically and consumes only the
	// selected presentation response; uses the asynchronous UI RNG.
	CvString getDynamicDiplomacyTextForPlayers(PlayerTypes eAIPlayer, PlayerTypes eOtherPlayer, DiploCommentTypes eComment) const;

	// Pure main-thread inspection; these getters do not consume response uses.
	int getNumResponses(PlayerTypes eAIPlayer, DiploCommentTypes eComment) const;
	bool isResponseForCivilization(PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex) const;
	bool isResponseForLeaderHead(PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex) const;
	bool isResponseForAttitude(PlayerTypes eAIPlayer, PlayerTypes eOtherPlayer, DiploCommentTypes eComment, int iGroupIndex) const;
	bool isResponseForDiplomacyPower(PlayerTypes eAIPlayer, PlayerTypes eOtherPlayer, DiploCommentTypes eComment, int iGroupIndex) const;
	int getNumDiplomacyText(PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex) const;
	CvString getDiplomacyText(PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex, int iVariant) const;

private:
	// Static lightweight unique class - no creation, no copying, no assignment, no deletion
	// Construct on the game thread before starting the worker. Stop and join the
	// worker before DLL unload; a critical section does not extend object lifetime.
	CvDynamicDiploManager() : m_dwMainThreadID(GetCurrentThreadId()), m_bInitialized(false), m_iNumDiploCommentTypes(0),
		m_ulSessionID(0), m_iMailboxHead(0), m_iMailboxCount(0) {};
	~CvDynamicDiploManager() {};
	CvDynamicDiploManager(CvDynamicDiploManager const& kOther);
	CvDynamicDiploManager& operator=(CvDynamicDiploManager const& kOther);

	void updateAIPlayerAvailableResponses(LLMResultData const& kResult); // Main-thread mailbox import only.
	void init();
	void reset();
	void uninit();

	mutable CvCriticalSection m_CS;

	std::vector<std::vector<DynamicResponse*> > m_LLMDiploResponses; // not serialized into save game because responses are generated by LLM prompts
	typedef std::vector<char> RequestStates;
	mutable std::vector<std::vector<RequestStates> > m_aRequestStates; // 0 issued, 1 registered, 2 retired.
	DWORD m_dwMainThreadID;
	bool m_bInitialized;
	int m_iNumDiploCommentTypes;
	unsigned long m_ulSessionID;
	enum { MAX_QUEUED_RESULTS = 32, MAX_RESPONSE_BYTES = 4096,
		MAX_PENDING_PROMPTS = 128, MAX_GROUPS_PER_COMMENT = 256 };
	struct QueuedResult
	{
		unsigned long ulSession;
		PlayerTypes eAIPlayer;
		DiploCommentTypes eComment;
		int iGroupIndex;
		char szText[MAX_RESPONSE_BYTES + 1];
	};
	QueuedResult m_aMailbox[MAX_QUEUED_RESULTS];
	int m_iMailboxHead;
	int m_iMailboxCount;
	std::vector<LLMPromptData*> m_aPendingPrompts; // Main-thread ownership only.

	bool isMainThread() const { return GetCurrentThreadId() == m_dwMainThreadID; }
	void setInitialItems();
	void clearResponses(PlayerTypes eAIPlayer);
	char* getRequestState(PlayerTypes eAIPlayer, DiploCommentTypes eComment, int iGroupIndex) const; // Caller holds m_CS.
	DynamicResponse* getResponse(PlayerTypes eAIPlayer, DiploCommentTypes eComment) const; // Caller holds m_CS.
	bool getCivilizationTypes(PlayerTypes eAIPlayer, DiploCommentTypes eComment, CivilizationTypes eCiv, int iGroupIndex) const;
	bool getLeaderHeadTypes(PlayerTypes eAIPlayer, DiploCommentTypes eComment, LeaderHeadTypes eLeader, int iGroupIndex) const;
	bool getAttitudeTypes(PlayerTypes eAIPlayer, DiploCommentTypes eComment, AttitudeTypes eAttitude, int iGroupIndex) const;
	bool getDiplomacyPowerTypes(PlayerTypes eAIPlayer, DiploCommentTypes eComment, DiplomacyPowerTypes ePower, int iGroupIndex) const;
};

#define DIPLOMGR CvDynamicDiploManager::getConstInstance() // XANA (note): Game thread will be mostly reading from this class, mark it const for safety!

// XANA: 10-27-2026 LLM Text Diplomacy Generation - bounded worker mailbox
#endif
